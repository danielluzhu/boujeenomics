/**
 * Real model families and the real axes they vary along.
 *
 * Nothing here is invented: the family names, the variant axes (materials, sizes, dial
 * colours, canvases) and the eras are genuine product facts. What is NOT claimed here is a
 * tracked price history for any individual reference — see tools/generate-catalogue.ts for
 * exactly how each price path is derived, and the `modelled` label it carries throughout.
 *
 * `base` is the model's price level in `baseYear`, in USD.
 * `beta` is how hard the model moves with its category index (>1 = hype-sensitive).
 * `drift` is annual real price escalation above CPI, for retail items.
 * `from` is the first year the model could be bought at all.
 */

export interface Family {
  brand: string;
  name: string;
  category: string;
  kind: "retail" | "resale";
  base: number;
  baseYear?: number;
  beta?: number;
  drift?: number;
  from?: number;
  variants?: Variant[];
  note?: string;
}
export interface Variant {
  label: string;
  /** Price-level multiplier against the family's base. */
  mult: number;
  /** Multiplier on the family's beta. Material genuinely changes how hard a model moves:
   *  steel sports watches ran far ahead of their gold versions, and a concours car
   *  appreciates more than a driver. Without this, every variant of a family would report
   *  an identical return, differing only in price level. */
  bm?: number;
  from?: number;
}

